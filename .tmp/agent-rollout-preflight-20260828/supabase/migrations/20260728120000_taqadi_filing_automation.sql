-- Durable queue and audit trail for filing legal cases in Taqadi through a
-- trusted local Playwright worker.

CREATE TABLE IF NOT EXISTS public.taqadi_filing_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  legal_case_id uuid NOT NULL REFERENCES public.legal_cases(id) ON DELETE CASCADE,
  contract_id uuid NOT NULL REFERENCES public.contracts(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'queued' CHECK (
    status IN (
      'queued',
      'validating',
      'waiting_login',
      'filling_case',
      'validating_parties',
      'uploading_documents',
      'reviewing',
      'submitting',
      'filed',
      'needs_human',
      'failed',
      'cancelled'
    )
  ),
  current_step text NOT NULL DEFAULT 'queued',
  progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  result jsonb,
  error_code text,
  error_message text,
  idempotency_key text NOT NULL,
  automation_version text NOT NULL DEFAULT 'taqadi-v1',
  final_approval boolean NOT NULL DEFAULT true,
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  max_attempts integer NOT NULL DEFAULT 3 CHECK (max_attempts BETWEEN 1 AND 10),
  locked_by text,
  locked_at timestamptz,
  heartbeat_at timestamptz,
  requested_by uuid NOT NULL,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, idempotency_key)
);
CREATE TABLE IF NOT EXISTS public.taqadi_filing_job_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  job_id uuid NOT NULL REFERENCES public.taqadi_filing_jobs(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  step text,
  status text,
  message text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.taqadi_filing_artifacts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  job_id uuid NOT NULL REFERENCES public.taqadi_filing_jobs(id) ON DELETE CASCADE,
  artifact_type text NOT NULL CHECK (
    artifact_type IN ('screenshot', 'receipt', 'submission_summary', 'error_snapshot')
  ),
  storage_path text NOT NULL,
  file_name text NOT NULL,
  mime_type text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.taqadi_automation_workers (
  worker_id text PRIMARY KEY,
  status text NOT NULL DEFAULT 'offline' CHECK (
    status IN ('idle', 'busy', 'waiting_login', 'error', 'offline')
  ),
  version text NOT NULL,
  current_job_id uuid REFERENCES public.taqadi_filing_jobs(id) ON DELETE SET NULL,
  hostname text,
  last_error text,
  started_at timestamptz NOT NULL DEFAULT now(),
  heartbeat_at timestamptz NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_taqadi_filing_jobs_queue
  ON public.taqadi_filing_jobs(status, created_at)
  WHERE status = 'queued';
CREATE INDEX IF NOT EXISTS idx_taqadi_filing_jobs_case
  ON public.taqadi_filing_jobs(company_id, legal_case_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_taqadi_filing_jobs_contract
  ON public.taqadi_filing_jobs(company_id, contract_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_taqadi_filing_jobs_active_case
  ON public.taqadi_filing_jobs(company_id, legal_case_id)
  WHERE status NOT IN ('filed', 'failed', 'cancelled');
CREATE INDEX IF NOT EXISTS idx_taqadi_filing_events_job
  ON public.taqadi_filing_job_events(job_id, created_at);
CREATE INDEX IF NOT EXISTS idx_taqadi_filing_artifacts_job
  ON public.taqadi_filing_artifacts(job_id, created_at);
