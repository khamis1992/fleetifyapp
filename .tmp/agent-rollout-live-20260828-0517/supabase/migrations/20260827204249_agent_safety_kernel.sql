CREATE OR REPLACE FUNCTION public.contract_terms_scan_batch_candidates_v4(
  p_company_id uuid,
  p_limit integer DEFAULT 4,
  p_contract_id uuid DEFAULT NULL
)
RETURNS TABLE (
  contract_id uuid,
  company_id uuid,
  document_id uuid,
  contract_number text,
  contract_amount numeric,
  expected_amount numeric,
  trigger_reason text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  WITH candidate AS (
    SELECT
      contract.id AS contract_id,
      contract.company_id,
      document.id AS document_id,
      contract.contract_number,
      contract.contract_amount,
      COALESCE(NULLIF(graph.schedule_total, 0), date_graph.expected_amount) AS expected_amount,
      CASE
        WHEN graph.missing_invoice_count > 0 THEN 'active_schedule_missing_invoice'
        WHEN graph.active_schedule_count > 0 AND graph.active_invoice_count = 0
          THEN 'schedule_graph_without_invoices'
        WHEN failed_repair.has_failed_repair THEN 'audit_repair_requires_document_decision'
        ELSE 'contract_amount_graph_mismatch'
      END AS trigger_reason,
      CASE
        WHEN graph.missing_invoice_count > 0 THEN 1
        WHEN graph.active_schedule_count > 0 AND graph.active_invoice_count = 0 THEN 2
        WHEN failed_repair.has_failed_repair THEN 3
        ELSE 4
      END AS priority_rank,
      contract.updated_at
    FROM public.contracts contract
    JOIN LATERAL (
      SELECT doc.id
      FROM public.contract_documents doc
      WHERE doc.contract_id = contract.id
        AND doc.company_id = contract.company_id
        AND doc.document_type IN ('signed_contract', 'signed_contract_image')
        AND doc.file_path IS NOT NULL
        AND doc.legal_identity_match_status = 'matched'
      ORDER BY doc.created_at DESC, doc.id
      LIMIT 1
    ) document ON true
    CROSS JOIN LATERAL (
      SELECT round(
        contract.monthly_amount * GREATEST(1, (
          (EXTRACT(YEAR FROM date_trunc('month', contract.end_date))
            - EXTRACT(YEAR FROM date_trunc('month', contract.start_date))) * 12
          + EXTRACT(MONTH FROM date_trunc('month', contract.end_date))
          - EXTRACT(MONTH FROM date_trunc('month', contract.start_date))
          + 1
        )::integer),
        2
      ) AS expected_amount
    ) date_graph
    CROSS JOIN LATERAL (
      SELECT
        count(*) FILTER (
          WHERE lower(COALESCE(schedule.status, '')) NOT IN (
            'cancelled', 'canceled', 'void', 'voided', 'deleted', 'inactive'
          )
        )::integer AS active_schedule_count,
        COALESCE(sum(schedule.amount) FILTER (
          WHERE lower(COALESCE(schedule.status, '')) NOT IN (
            'cancelled', 'canceled', 'void', 'voided', 'deleted', 'inactive'
          )
        ), 0)::numeric AS schedule_total,
        count(*) FILTER (
          WHERE lower(COALESCE(schedule.status, '')) NOT IN (
            'cancelled', 'canceled', 'void', 'voided', 'deleted', 'inactive'
          )
            AND schedule.invoice_id IS NULL
        )::integer AS missing_invoice_count,
        (
          SELECT count(*)::integer
          FROM public.invoices invoice
          WHERE invoice.company_id = contract.company_id
            AND invoice.contract_id = contract.id
            AND COALESCE(invoice.total_amount, 0) > 0.01
            AND lower(COALESCE(invoice.status, '')) NOT IN (
              'cancelled', 'canceled', 'void', 'voided', 'deleted', 'inactive'
            )
            AND lower(COALESCE(invoice.payment_status, '')) NOT IN (
              'cancelled', 'canceled', 'void', 'voided', 'deleted', 'inactive'
            )
        ) AS active_invoice_count
      FROM public.contract_payment_schedules schedule
      WHERE schedule.company_id = contract.company_id
        AND schedule.contract_id = contract.id
    ) graph
    CROSS JOIN LATERAL (
      SELECT EXISTS (
        SELECT 1
        FROM public.system_agent_findings finding
        WHERE finding.company_id = contract.company_id
          AND finding.code = 'schedule.missing_invoice'
          AND finding.status = 'failed'
          AND finding.evidence ->> 'contractId' = contract.id::text
      ) AS has_failed_repair
    ) failed_repair
    WHERE contract.company_id = p_company_id
      AND (p_contract_id IS NULL OR contract.id = p_contract_id)
      AND contract.status IN ('active', 'under_legal_procedure')
      AND COALESCE(contract.monthly_amount, 0) > 0
      AND contract.start_date IS NOT NULL
      AND contract.end_date IS NOT NULL
      AND contract.end_date >= contract.start_date
      AND (
        graph.missing_invoice_count > 0
        OR (graph.active_schedule_count > 0 AND graph.active_invoice_count = 0)
        OR failed_repair.has_failed_repair
        OR abs(contract.contract_amount - COALESCE(NULLIF(graph.schedule_total, 0), date_graph.expected_amount)) > 1
      )
      AND NOT EXISTS (
        SELECT 1
        FROM public.contract_terms_scan_proposals proposal
        WHERE proposal.contract_id = contract.id
          AND proposal.status = 'applied'
          AND proposal.updated_at > now() - interval '1 day'
      )
  )
  SELECT
    candidate.contract_id,
    candidate.company_id,
    candidate.document_id,
    candidate.contract_number,
    candidate.contract_amount,
    candidate.expected_amount,
    candidate.trigger_reason
  FROM candidate
  ORDER BY candidate.priority_rank, candidate.updated_at, candidate.contract_id
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 4), 1), 25);
$function$;

REVOKE ALL ON FUNCTION public.contract_terms_scan_batch_candidates_v4(uuid,integer,uuid)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.contract_terms_scan_batch_candidates_v4(uuid,integer,uuid)
TO service_role;

CREATE OR REPLACE FUNCTION public.assert_direct_legal_contract_document_v1(
  p_company_id uuid,
  p_contract_id uuid,
  p_document_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_document public.contract_documents%ROWTYPE;
BEGIN
  SELECT document.*
  INTO v_document
  FROM public.contract_documents document
  WHERE document.id = p_document_id
    AND document.company_id = p_company_id
    AND document.contract_id = p_contract_id
    AND document.document_type IN ('signed_contract', 'signed_contract_image')
    AND NULLIF(BTRIM(document.file_path), '') IS NOT NULL;

  IF v_document.id IS NULL THEN
    RETURN jsonb_build_object('allowed', false, 'reason', 'document_not_directly_attached');
  END IF;
  IF v_document.legal_identity_match_status <> 'matched' THEN
    RETURN jsonb_build_object(
      'allowed', false,
      'reason', 'identity_not_matched',
      'status', v_document.legal_identity_match_status
    );
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.contract_documents other
    WHERE other.company_id = p_company_id
      AND other.id <> v_document.id
      AND other.file_path = v_document.file_path
      AND other.document_type IN ('signed_contract', 'signed_contract_image')
      AND other.contract_id <> p_contract_id
  ) THEN
    RETURN jsonb_build_object('allowed', false, 'reason', 'storage_file_reused_across_contracts');
  END IF;

  RETURN jsonb_build_object(
    'allowed', true,
    'reason', 'direct_identity_matched_document',
    'documentId', v_document.id,
    'contractId', v_document.contract_id,
    'filePath', v_document.file_path
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.assert_direct_legal_contract_document_v1(uuid,uuid,uuid)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.assert_direct_legal_contract_document_v1(uuid,uuid,uuid)
TO service_role;

CREATE OR REPLACE FUNCTION public.get_agent_safety_inventory_v1()
RETURNS TABLE (
  agent_id text,
  display_name text,
  execution_mode text,
  risk_level text,
  conflict_group text,
  policy_enabled boolean,
  invocation_enabled boolean,
  cron_job_id bigint,
  cron_active boolean,
  schedule text,
  lease_company_id uuid,
  lease_owner_agent_id text,
  lease_expires_at timestamptz,
  last_safety_event_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT
    policy.agent_id,
    policy.display_name,
    policy.execution_mode,
    policy.risk_level,
    policy.conflict_group,
    policy.enabled AS policy_enabled,
    registry.enabled AS invocation_enabled,
    cron.jobid AS cron_job_id,
    cron.active AS cron_active,
    cron.schedule,
    lease.company_id AS lease_company_id,
    lease.agent_id AS lease_owner_agent_id,
    lease.expires_at AS lease_expires_at,
    (
      SELECT max(event.created_at)
      FROM public.agent_safety_events event
      WHERE event.agent_id = policy.agent_id
    ) AS last_safety_event_at
  FROM public.agent_safety_policies policy
  LEFT JOIN public.agent_invocation_registry registry
    ON registry.agent_id = policy.agent_id
  LEFT JOIN cron.job cron
    ON cron.jobname = policy.schedule_name
  LEFT JOIN public.agent_invocation_leases lease
    ON lease.conflict_group = policy.conflict_group
   AND lease.expires_at > now();
$function$;

REVOKE ALL ON FUNCTION public.get_agent_safety_inventory_v1()
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_agent_safety_inventory_v1()
TO service_role;

