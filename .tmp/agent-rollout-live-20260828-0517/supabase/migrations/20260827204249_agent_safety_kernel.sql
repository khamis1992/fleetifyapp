CREATE TABLE public.agent_safety_policies (
  agent_id text PRIMARY KEY,
  schedule_name text NULL UNIQUE,
  display_name text NOT NULL,
  execution_mode text NOT NULL
    CHECK (execution_mode IN ('observe', 'propose', 'auto_apply')),
  risk_level text NOT NULL
    CHECK (risk_level IN ('low', 'medium', 'high', 'critical')),
  conflict_group text NOT NULL,
  max_runtime_seconds integer NOT NULL DEFAULT 600
    CHECK (max_runtime_seconds BETWEEN 10 AND 3600),
  minimum_confidence numeric NOT NULL DEFAULT 1
    CHECK (minimum_confidence BETWEEN 0 AND 1),
  requires_direct_entity_link boolean NOT NULL DEFAULT true,
  allows_cross_entity_evidence boolean NOT NULL DEFAULT false,
  evidence_policy jsonb NOT NULL DEFAULT '{}'::jsonb,
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.agent_invocation_leases (
  company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  conflict_group text NOT NULL,
  agent_id text NOT NULL REFERENCES public.agent_safety_policies(agent_id) ON DELETE RESTRICT,
  request_id text NOT NULL,
  acquired_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  PRIMARY KEY (company_id, conflict_group)
);

CREATE INDEX agent_invocation_leases_expiry_idx
  ON public.agent_invocation_leases(expires_at);

CREATE TABLE public.agent_safety_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NULL REFERENCES public.companies(id) ON DELETE SET NULL,
  agent_id text NOT NULL REFERENCES public.agent_safety_policies(agent_id) ON DELETE RESTRICT,
  request_id text NULL,
  operation text NOT NULL,
  entity_type text NULL,
  entity_id text NULL,
  outcome text NOT NULL
    CHECK (outcome IN ('allowed', 'blocked', 'busy', 'duplicate', 'succeeded', 'failed', 'timed_out')),
  reason_code text NOT NULL,
  confidence numeric NULL CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

