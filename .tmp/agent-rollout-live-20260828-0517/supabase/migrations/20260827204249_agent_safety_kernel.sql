CREATE OR REPLACE FUNCTION public.verify_scheduled_agent_invocation_v2(
  p_agent_id text,
  p_company_id uuid,
  p_supplied_secret text,
  p_request_id text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_policy public.agent_safety_policies%ROWTYPE;
  v_request_id text := NULLIF(pg_catalog.left(COALESCE(p_request_id, ''), 200), '');
  v_claimed boolean := false;
BEGIN
  IF NOT public.verify_scheduled_agent_invocation_v1(
    p_agent_id,
    p_company_id,
    p_supplied_secret,
    v_request_id
  ) THEN
    RETURN false;
  END IF;

  SELECT policy.*
  INTO v_policy
  FROM public.agent_safety_policies policy
  WHERE policy.agent_id = p_agent_id
    AND policy.enabled = true;

  IF v_policy.agent_id IS NULL OR p_company_id IS NULL OR v_request_id IS NULL THEN
    RETURN false;
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'agent-invocation:' || p_company_id::text || ':' || v_policy.conflict_group,
      0
    )
  );

  IF EXISTS (
    SELECT 1
    FROM public.agent_safety_events event
    WHERE event.company_id = p_company_id
      AND event.agent_id = p_agent_id
      AND event.request_id = v_request_id
      AND event.operation = 'scheduled_invocation'
      AND event.outcome = 'allowed'
  ) THEN
    INSERT INTO public.agent_safety_events (
      company_id,
      agent_id,
      request_id,
      operation,
      outcome,
      reason_code,
      confidence,
      evidence
    ) VALUES (
      p_company_id,
      p_agent_id,
      v_request_id,
      'scheduled_invocation',
      'duplicate',
      'request_id_already_allowed',
      1,
      jsonb_build_object('conflict_group', v_policy.conflict_group)
    );
    RETURN false;
  END IF;

  DELETE FROM public.agent_invocation_leases lease
  WHERE lease.company_id = p_company_id
    AND lease.conflict_group = v_policy.conflict_group
    AND lease.expires_at <= now();

  INSERT INTO public.agent_invocation_leases (
    company_id,
    conflict_group,
    agent_id,
    request_id,
    expires_at
  ) VALUES (
    p_company_id,
    v_policy.conflict_group,
    p_agent_id,
    v_request_id,
    now() + pg_catalog.make_interval(secs => v_policy.max_runtime_seconds)
  )
  ON CONFLICT (company_id, conflict_group) DO UPDATE
  SET agent_id = EXCLUDED.agent_id,
      request_id = EXCLUDED.request_id,
      acquired_at = now(),
      expires_at = EXCLUDED.expires_at
  WHERE public.agent_invocation_leases.request_id = EXCLUDED.request_id
  RETURNING true INTO v_claimed;

  INSERT INTO public.agent_safety_events (
    company_id,
    agent_id,
    request_id,
    operation,
    outcome,
    reason_code,
    confidence,
    evidence
  ) VALUES (
    p_company_id,
    p_agent_id,
    v_request_id,
    'scheduled_invocation',
    CASE WHEN v_claimed THEN 'allowed' ELSE 'busy' END,
    CASE WHEN v_claimed THEN 'machine_identity_and_policy_valid' ELSE 'conflict_group_lease_active' END,
    1,
    jsonb_build_object('conflict_group', v_policy.conflict_group)
  );

  RETURN v_claimed;
END;
$function$;

