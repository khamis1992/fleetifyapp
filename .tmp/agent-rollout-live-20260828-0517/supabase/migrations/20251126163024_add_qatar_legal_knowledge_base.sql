-- إنشاء جدول قاعدة المعرفة القانونية
CREATE TABLE IF NOT EXISTS legal_knowledge_base (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  category VARCHAR(100) NOT NULL,
  subcategory VARCHAR(100),
  law_name VARCHAR(255) NOT NULL,
  law_number VARCHAR(50),
  law_year INTEGER,
  article_number VARCHAR(20),
  article_title VARCHAR(255),
  article_content TEXT NOT NULL,
  country VARCHAR(50) DEFAULT 'qatar',
  is_active BOOLEAN DEFAULT TRUE,
  keywords TEXT[],
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- إضافة فهارس للبحث السريع
CREATE INDEX IF NOT EXISTS idx_legal_kb_category ON legal_knowledge_base(category);
CREATE INDEX IF NOT EXISTS idx_legal_kb_country ON legal_knowledge_base(country);
CREATE INDEX IF NOT EXISTS idx_legal_kb_keywords ON legal_knowledge_base USING GIN(keywords);

