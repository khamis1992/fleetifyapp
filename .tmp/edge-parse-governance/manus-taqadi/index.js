Deno.serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }
  return new Response(
    JSON.stringify({
      success: false,
      error: "LEGACY_TAQADI_BYPASS_RETIRED",
      message: "\u0627\u0633\u062A\u062E\u062F\u0645 \u0648\u0643\u064A\u0644 \u062A\u0642\u0627\u0636\u064A \u0627\u0644\u0645\u062D\u0644\u064A \u0648\u0637\u0627\u0628\u0648\u0631 taqadi_filing_jobs \u0627\u0644\u0645\u062D\u0643\u0648\u0645."
    }),
    { status: 410, headers: { ...corsHeaders, "Content-Type": "application/json" } }
  );
  try {
    if (!MANUS_API_KEY) {
      throw new Error("MANUS_API_KEY not configured");
    }
    const { lawsuitData } = await req.json();
    if (!lawsuitData) {
      throw new Error("lawsuitData is required");
    }
    const prompt = generateTaqadiPrompt(lawsuitData);
    console.log("Sending task to Manus API...");
    console.log("Prompt length:", prompt.length);
    const response = await fetch(MANUS_API_URL, {
      method: "POST",
      headers: {
        "accept": "application/json",
        "content-type": "application/json",
        "API_KEY": MANUS_API_KEY
      },
      body: JSON.stringify({
        prompt,
        // Use 'agent' mode for full browser automation capabilities
        taskMode: "agent",
        // Specify agent profile for quality
        agentProfile: "quality",
        // Use local browser connector instead of cloud browser
        connectors: ["be268223-40b2-4f3c-a907-c12eb1699283"],
        // My Browser connector
        // Additional metadata
        metadata: {
          source: "fleetify-app",
          type: "taqadi-lawsuit",
          contractNumber: lawsuitData.vehicle.contractNumber,
          defendantName: lawsuitData.defendant.name,
          amount: lawsuitData.amounts.total
        }
      })
    });
    if (!response.ok) {
      const errorText = await response.text();
      console.error("Manus API error:", errorText);
      throw new Error(`Manus API error: ${response.status} - ${errorText}`);
    }
    const result = await response.json();
    console.log("Manus task created:", result);
    return new Response(
      JSON.stringify({
        success: true,
        taskId: result.task_id,
        taskUrl: result.task_url,
        message: "\u062A\u0645 \u0625\u0631\u0633\u0627\u0644 \u0627\u0644\u0645\u0647\u0645\u0629 \u0625\u0644\u0649 Manus! \u0633\u064A\u0641\u062A\u062D \u0645\u062A\u0635\u0641\u062D\u0643 \u0642\u0631\u064A\u0628\u0627\u064B.\n\n\u{1F517} \u0634\u0627\u0647\u062F \u0627\u0644\u0645\u0647\u0645\u0629: " + result.task_url,
        manusResponse: result
      }),
      {
        headers: {
          ...corsHeaders,
          "Content-Type": "application/json"
        }
      }
    );
  } catch (error) {
    console.error("Error:", error);
    return new Response(
      JSON.stringify({
        success: false,
        error: error.message
      }),
      {
        status: 500,
        headers: {
          ...corsHeaders,
          "Content-Type": "application/json"
        }
      }
    );
  }
});
